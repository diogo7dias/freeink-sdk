constexpr uint8_t X3_LUT_LEN = 42;

// Bank invariants, checked at build time. The five tables of a bank run as one waveform, so
// they must agree on every timing byte of every group (bytes 1..5 of each 6-byte group;
// byte 0 is the per-phase level, which is what differs between cells). A bank that drifts
// apart here drives some transition cells for longer than others and shows up on the panel
// as ghosting that no software path explains.
constexpr bool x3TimingAgrees(const uint8_t* a, const uint8_t* b) {
  for (int i = 0; i < X3_LUT_LEN; i++)
    if (i % 6 != 0 && a[i] != b[i]) return false;
  return true;
}
constexpr bool x3SameTable(const uint8_t* a, const uint8_t* b) {
  for (int i = 0; i < X3_LUT_LEN; i++)
    if (a[i] != b[i]) return false;
  return true;
}
// The scrub bank's contract: WW == BW and WB == BB (the old frame is ignored), and each
// target opens with a pulse toward the opposite rail (see _half above).
static_assert(x3SameTable(lut_x3_ww_half, lut_x3_bw_half) && x3SameTable(lut_x3_wb_half, lut_x3_bb_half),
              "_half must drive every pixel to its target whatever it held");
static_assert((lut_x3_ww_half[0] >> 6) == 0x1 && (lut_x3_wb_half[0] >> 6) == 0x2,
              "_half must open with an opposite-rail pulse: black before white, white before black");
#define X3_BANK_TIMING_AGREES(bank)                                                                             \
  static_assert(x3TimingAgrees(lut_x3_vcom_##bank, lut_x3_ww_##bank) &&                                         \
                    x3TimingAgrees(lut_x3_vcom_##bank, lut_x3_bw_##bank) &&                                     \
                    x3TimingAgrees(lut_x3_vcom_##bank, lut_x3_wb_##bank) &&                                     \
                    x3TimingAgrees(lut_x3_vcom_##bank, lut_x3_bb_##bank),                                       \
                #bank " bank: the five tables disagree on timing")
X3_BANK_TIMING_AGREES(normal);
X3_BANK_TIMING_AGREES(half);
X3_BANK_TIMING_AGREES(fast);
X3_BANK_TIMING_AGREES(full);
X3_BANK_TIMING_AGREES(gc);
X3_BANK_TIMING_AGREES(aa_pre_bw_mid);
#undef X3_BANK_TIMING_AGREES

