// --- _half: scrub bank (WW==BW, WB==BB) ---
// Drives every pixel to its target whatever it held, so DTM1 is ignored. Each table opens
// with a short pulse toward the OPPOSITE rail (group 0: X3_HALF_REVERSE_FRAMES) and then runs the old
// same-rail drive unchanged (groups 1 and 2: 24 frames white or black, then the 5 trailing
// frames of the old bank).
//
// Why the opening pulse: the bank used to be same-rail only, so a pixel that was already
// at its target (the vast majority of a page) took 24 frames of extra drive in the one
// direction and never left its rail. That saturates, it does not discharge: trapped charge
// is shifted by a reversal, not by more of the same, and the same-direction overdrive is
// DC the pixel keeps. The pulse is the reversal, and it makes the bank DC-neutral for the
// pixels that do not change. Costs X3_HALF_REVERSE_FRAMES frames (about 31 ms each at the
// 0x09 frame clock, measured from the 566 ms 18-frame FAST) on a pass the policy runs once
// per thirteen page turns.
//
// Calibration knob: a full black/white swing takes 12 to 18 frames on this panel (FAST moves
// a pixel in 18 and shows haze from about 11), so 10 is most of a swing. Raise it if a
// ghost survives the clean, lower it if the clean flashes too visibly; build with
// -DFREEINK_X3_HALF_REVERSE_FRAMES=n.
//
// Level codes per phase (bits 7:6 phase A .. 1:0 phase D): 01 = black rail, 10 = white
// rail. Group layout: levels, T_A, T_B, T_C, T_D, repeat.
#ifndef FREEINK_X3_HALF_REVERSE_FRAMES
#define FREEINK_X3_HALF_REVERSE_FRAMES 10
#endif
static_assert(FREEINK_X3_HALF_REVERSE_FRAMES > 0 && FREEINK_X3_HALF_REVERSE_FRAMES <= 40,
              "reverse pulse of the _half bank: 1..40 frames");
constexpr uint8_t X3_HALF_REVERSE_FRAMES = FREEINK_X3_HALF_REVERSE_FRAMES;
